function getPrograms(운영ID) {
  return DB_PROGRAMS.filter(p => p.운영ID === 운영ID).sort((a,b) => a.순번 - b.순번);
}

function getProgramSummary(운영ID) {
  const progs = getPrograms(운영ID);
  if (!progs.length) return '-';
  const names = progs.map(p => p.프로그램명).join(' · ');
  return `${names} (${progs.length}종)`;
}

function getProgramCount(운영ID) {
  return DB_PROGRAMS.filter(p => p.운영ID === 운영ID).length;
}

